const simulationVideos = {
  libero: liberoSuites.flatMap(({ directory, files }) =>
    files.map((file) => `assets/videos/libero/${directory}/${file}`),
  ),
  robotwin: robotwinFiles.map((file) => `assets/videos/robotwin/${file}`),
};

const labelFromPath = (path) =>
  path
    .split("/")
    .pop()
    .replace(/\.mp4$/i, "")
    .replace(/^task\d+_/, "")
    .replace(/_success$/, "")
    .replaceAll("_", " ");

const playVideos = (container) => {
  container.querySelectorAll("video").forEach((video) => {
    video.play().catch(() => {});
  });
};

const pauseVideos = (container) => {
  container.querySelectorAll("video").forEach((video) => video.pause());
};

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll("[data-video-group]").forEach((gallery) => {
    const paths = simulationVideos[gallery.dataset.videoGroup] ?? [];
    const fragment = document.createDocumentFragment();

    paths.forEach((path) => {
      const video = document.createElement("video");
      const label = labelFromPath(path);
      video.src = path;
      video.loop = true;
      video.muted = true;
      video.playsInline = true;
      video.preload = "metadata";
      video.tabIndex = -1;
      video.title = label;
      video.setAttribute("aria-label", label);
      video.setAttribute("disablepictureinpicture", "");
      fragment.appendChild(video);
    });

    gallery.appendChild(fragment);
  });

  const videoGroups = document.querySelectorAll(".real-world-grid, [data-video-group]");
  if (!("IntersectionObserver" in window)) {
    videoGroups.forEach(playVideos);
    return;
  }

  const playbackObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          playVideos(entry.target);
        } else {
          pauseVideos(entry.target);
        }
      });
    },
    { rootMargin: "160px 0px", threshold: 0.01 },
  );

  videoGroups.forEach((group) => playbackObserver.observe(group));
});
